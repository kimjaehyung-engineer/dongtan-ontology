    count = 0
    for fld in folders:
        num = int(fld.split('_')[0]) if fld.split('_')[0].isdigit() else 999
        name = '_'.join(fld.split('_')[1:])
        data = get_task_data(num, name)

        sub_types = [
            ("표준서", f"{name}_표준서.html", generate_standard_html),
            ("수행지침", f"{name}_수행지침.html", generate_guideline_html),
            ("체크리스트", f"{name}_체크리스트.html", generate_checklist_html)
        ]

        for sub, fn, gen_func in sub_types:
            dir_path = os.path.join(BASE_DIR, fld, sub)
            os.makedirs(dir_path, exist_ok=True)
            fp = os.path.join(dir_path, fn)
            content = gen_func(num, fld, data)
            with open(fp, "w", encoding="utf-8") as f:
                f.write(content)
            count += 1

        print(f"[{num:2d}/50] Successfully built WBS 9000-2-{num:<2d} ({name})")

    print(f"\n=== Completed: {count} Architecture HTML files generated! ===")

