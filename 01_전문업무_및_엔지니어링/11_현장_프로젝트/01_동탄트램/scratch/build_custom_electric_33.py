def main():
    print("=== Re-generating 33 Electric Tasks with 100% 1:1 Tailored Engineering Content ===")
    tasks_list = get_full_33_tasks()
    total_generated = 0

    for item in tasks_list:
        task = build_task_dict(item)
        num = task["num"]
        folder_name = task["folder"]
        task_dir = os.path.join(BASE_DIR, folder_name)

        if not os.path.exists(task_dir):
            print(f"Directory not found: {task_dir}")
            continue

        std_dir = os.path.join(task_dir, "표준서")
        gd_dir = os.path.join(task_dir, "수행지침")
        chk_dir = os.path.join(task_dir, "체크리스트")

        os.makedirs(std_dir, exist_ok=True)
        os.makedirs(gd_dir, exist_ok=True)
        os.makedirs(chk_dir, exist_ok=True)

        # 1. 표준서
        std_content = render_standard_html(task)
        std_file = os.path.join(std_dir, f"{task['name']}_표준서.html")
        with open(std_file, "w", encoding="utf-8") as f:
            f.write(std_content)
        total_generated += 1

        # 2. 수행지침
        gd_content = render_guideline_html(task)
        gd_file = os.path.join(gd_dir, f"{task['name']}_수행지침.html")
        with open(gd_file, "w", encoding="utf-8") as f:
            f.write(gd_content)
        total_generated += 1

        # 3. 체크리스트
        chk_content = render_checklist_html(task)
        chk_file = os.path.join(chk_dir, f"{task['name']}_체크리스트.html")
        with open(chk_file, "w", encoding="utf-8") as f:
            f.write(chk_content)
        total_generated += 1

        # 33번 Task_33 호환 파일 동기화
        if num == 33:
            for sub, fn_name in [("표준서", "Task_33_표준서.html"), ("수행지침", "Task_33_수행지침.html"), ("체크리스트", "Task_33_체크리스트.html")]:
                content = std_content if sub == "표준서" else (gd_content if sub == "수행지침" else chk_content)
                with open(os.path.join(task_dir, sub, fn_name), "w", encoding="utf-8") as f:
                    f.write(content)

        print(f"[{num:2d}/33] Successfully built 1:1 tailored WBS {task['wbs']:9s} ({task['name']})")

    print(f"\n=== Completed: {total_generated} 1:1 Tailored HTML files generated! ===")

if __name__ == "__main__":
    main()
